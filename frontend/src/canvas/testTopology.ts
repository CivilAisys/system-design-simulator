import type { Topology } from '@/api/client'

// 原型：比較流量呈現方式用的複雜拓撲（prototype/visual-refresh，不合併）。
// 十六個節點，流量從幾十到幾十萬 rps：LB 扇出、Cache、讀寫分離、MQ、外部 API、CDN、Rate Limiter 都有
const svc = (instances: number, concurrency: number, serviceTimeMs: number) => ({
  instances,
  concurrency,
  serviceTimeMs,
  callMode: 'SEQUENTIAL' as const,
})

const edge = (id: string, source: string, target: string, extra: Partial<Topology['edges'][number]> = {}) => ({
  id,
  source,
  target,
  weight: 1,
  callsPerRequest: 1,
  latencyMs: 1,
  requestClass: 'ALL' as const,
  ...extra,
})

